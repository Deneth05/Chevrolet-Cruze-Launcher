window.describeDtc = function (code) {
  if (DTC_DB[code]) return DTC_DB[code];
  var fam = { P: 'Powertrain', C: 'Chassis', B: 'Body', U: 'Network' }[code.charAt(0)] || 'Unknown';
  var maker = code.charAt(1) === '1' || code.charAt(1) === '3' ? ' (manufacturer specific)' : '';
  return fam + ' fault' + maker;
};
